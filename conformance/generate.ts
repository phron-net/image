const key = "5c8a1f0e9b7d4a3c2e6f8091a2b3c4d5e6f708192a3b4c5d6e7f8091a2b3c4d5";
const salt = "a1b2c3d4e5f60718293a4b5c6d7e8f90";
const base = "https://acme.phronusercontent.com";
const enc = (p: string): string =>
  p.replace(/^\/+/, "").split("/").map(encodeURIComponent).join("/");
const plain = (p: string, f?: string): string =>
  `plain/${enc(p)}${f ? `@${encodeURIComponent(f)}` : ""}`;
const path = (opts: string[], p: string, f?: string): string =>
  `/${[...opts.filter((o) => o !== ""), plain(p, f)].join("/")}`;
const sig = (signed: string): string =>
  createHmac("sha256", Buffer.from(key, "hex"))
    .update(Buffer.from(salt, "hex"))
    .update(signed)
    .digest("base64url");

interface SignCase {
  name: string;
  options: string[];
  path: string;
  format?: string;
  expiresAt?: number;
  baseUrl?: string;
  label?: string;
  signedPath?: string;
  url?: string;
}

